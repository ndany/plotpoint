#!/usr/bin/env python3
"""Re-render docs/examples/library-review/ from the fixture's reference storyboard.

Run after any rendering change, then look at the output:
    .venv/bin/python scripts/build_examples.py
"""

from __future__ import annotations

import json
import shutil
import sys
import tempfile
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
SCRIPTS = REPO / "plugins/plotpoint/skills/visualize/scripts"

FIXTURE = REPO / "tests/fixtures/library-review"
EXAMPLE = REPO / "docs/examples/library-review"
TARGETS = ["md/document", "html/document", "image/slide"]
SKIP = {"v4": ["image/slide"]}  # tables aren't slide images in v1
KEEP = (".svg", ".mmd", ".png")  # html fragments go into page.html instead

HEAD = """# Example: library services review (invented data)

Rendered by `plotpoint:visualize` from the reference storyboard of the test
fixture (`tests/fixtures/library-review/`). Every number is invented. Visuals
appear in the storyboard's order; the comment above each gives its placement and
audience. The same intents rendered for HTML are in [`page.html`](page.html),
and the charts have slide images in `figures/` (e.g.
[`v1-image-slide.png`](figures/v1/v1-image-slide.png)).

Generated by `scripts/build_examples.py`; don't edit by hand.
"""

PAGE = """<!doctype html>
<html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Library services review (invented data)</title>
<style>body{{margin:0;background:#fff;color:#1c1c1a;font:16px/1.5 system-ui,sans-serif}}
main{{max-width:960px;margin:0 auto;padding:32px 16px}}</style></head>
<body><main>
<h1>Library services review, FY26 (invented data)</h1>
<p>Each figure is a plotpoint <code>html/document</code> fragment, as-is.</p>
{figures}
</main></body></html>
"""


def main() -> int:
    sys.path.insert(0, str(SCRIPTS))
    from ppviz import docio, render

    with tempfile.TemporaryDirectory() as tmp:
        work = Path(tmp) / "work"
        shutil.copytree(FIXTURE, work, ignore=shutil.ignore_patterns("runs"))
        gold = docio.load(work / "storyboard-golden.yaml")
        datasets = {
            d["id"]: d for d in docio.load(work / "storyboard-request.yaml")["datasets"]
        }
        data_map = docio.load(work / "render-data.yaml")
        shutil.rmtree(EXAMPLE, ignore_errors=True)
        (EXAMPLE / "figures").mkdir(parents=True)
        md, html = [], []
        for v in gold["visuals"]:
            ds = datasets[v["datasets"][0]]
            req = {
                "id": v["id"],
                "intent": v["intent"],
                "data": data_map[v["id"]],
                "source": ds["source"],
                "as_of": ds["as_of"],
                "targets": [t for t in TARGETS if t not in SKIP.get(v["id"], [])],
                "technique": {t: r["technique"] for t, r in v["renderings"].items()},
                "color_map": gold["color_map"],
                "out_dir": f"figures/{v['id']}",
            }
            res = render.render(req, work)
            failed = [k for k, c in res["checks"].items() if c["status"] == "fail"]
            if failed:
                print(f"{v['id']}: checks failed: {failed}", file=sys.stderr)
                return 1
            for out in res["outputs"].values():
                for f in out["files"]:
                    if f.endswith(KEEP) and "html-document" not in f:
                        if f.endswith(".svg") and "image-slide" in f:
                            continue  # the PNG is the slide deliverable
                        dst = EXAMPLE / f
                        dst.parent.mkdir(parents=True, exist_ok=True)
                        shutil.copy(work / f, dst)
            aud = ", ".join(v["audience"])
            md.append(
                f"<!-- {v['id']}: {v['placement']}, for {aud} -->\n\n"
                + res["outputs"]["md/document"]["snippet"].strip()
            )
            html.append(res["outputs"]["html/document"]["snippet"].strip())
            print(
                v["id"], json.dumps({k: c["status"] for k, c in res["checks"].items()})
            )
        (EXAMPLE / "README.md").write_text(
            HEAD + "\n---\n\n" + "\n\n---\n\n".join(md) + "\n", encoding="utf-8"
        )
        (EXAMPLE / "page.html").write_text(
            PAGE.format(figures="\n".join(html)), encoding="utf-8"
        )
    return 0


if __name__ == "__main__":
    sys.exit(main())
